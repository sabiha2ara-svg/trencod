"""SQLite for local use; PostgreSQL for durable hosted storage.

This adapter accepts only Trencod's internal SQL, never user-supplied SQL.
Postgres uses a transaction-scoped writer lock for the beta marketplace's
multi-table operations. No fallback to temporary storage on connection errors.
"""
import os
import re
import sqlite3

class Row(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)

def row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))

def postgres_sql(sql):
    # Tokenize quoted strings so question marks/percent signs in literals stay intact.
    parts = re.split(r"('(?:''|[^'])*')", sql)
    for i in range(0, len(parts), 2):
        p = parts[i]
        p = re.sub(r'\bINTEGER PRIMARY KEY(?: AUTOINCREMENT)?', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', p, flags=re.I)
        p = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', p, flags=re.I)
        p = re.sub(r'\s+COLLATE NOCASE\b', '', p, flags=re.I)
        p = re.sub(r'\bLIKE\b', 'ILIKE', p, flags=re.I)
        p = p.replace('count=count+1', 'count=limits.count+1')
        p = p.replace('MAX(seen,excluded.seen)', 'GREATEST(inbox_seen.seen,excluded.seen)')
        parts[i] = p
    sql = ''.join(parts)
    if re.match(r'\s*INSERT OR IGNORE', sql, re.I):
        sql = re.sub(r'INSERT OR IGNORE', 'INSERT', sql, count=1, flags=re.I).rstrip().rstrip(';') + ' ON CONFLICT DO NOTHING'
    # Retain case-insensitive account names without a database extension.
    sql = re.sub(r'(FROM users WHERE )name=\?', r'\1lower(name)=lower(?)', sql, flags=re.I)
    return sql

class PostgresConnection:
    dialect = 'postgres'
    def __init__(self, url):
        import psycopg
        try:
            self.raw = psycopg.connect(url, connect_timeout=20, row_factory=row_factory, prepare_threshold=None)
        except psycopg.Error:
            raise RuntimeError('Database connection failed. Check DATABASE_URL in Render Environment; no local fallback was used.') from None
        self.locked = False
    def __enter__(self): return self
    def __exit__(self, typ, value, traceback):
        try:
            self.raw.rollback() if typ else self.raw.commit()
        finally: self.raw.close()
    def lock(self):
        if not self.locked:
            self.raw.execute("SET LOCAL lock_timeout = '20s'")
            self.raw.execute('SELECT pg_advisory_xact_lock(781320884)')
            self.locked = True
    def execute(self, sql, args=None):
        import psycopg
        if sql.strip().upper().startswith('PRAGMA'):
            return self.raw.execute('SELECT 1')
        if sql.strip().upper() == 'BEGIN IMMEDIATE':
            self.lock()
            return self.raw.execute('SELECT 1')
        if re.match(r'\s*(INSERT|UPDATE|DELETE|CREATE|ALTER|DROP)', sql, re.I): self.lock()
        sql = postgres_sql(sql)
        if args is not None:
            # psycopg placeholders; escape literal % also inside quoted SQL.
            parts = re.split(r"('(?:''|[^'])*')", sql.replace('%','%%'))
            for i in range(0,len(parts),2): parts[i] = parts[i].replace('?', '%s')
            sql = ''.join(parts)
        try: return self.raw.execute(sql, args)
        except psycopg.IntegrityError as exc:
            # Keep the public API's existing conflict/error handling.
            message = 'exclusive content conflict' if 'exclusive' in str(exc).lower() else 'Database integrity conflict'
            raise sqlite3.IntegrityError(message) from None
    def executescript(self, sql):
        # Schema scripts contain only plain table/index statements. PostgreSQL
        # functions/triggers are installed separately with raw.execute().
        for statement in sql.split(';'):
            if statement.strip(): self.execute(statement)
    def close(self): self.raw.close()

def connect(path):
    url = os.environ.get('DATABASE_URL','').strip()
    if url:
        if not url.startswith(('postgresql://','postgres://')):
            raise RuntimeError('DATABASE_URL must start with postgresql://. Paste only the connection URL, not a psql command.')
        return PostgresConnection(url)
    if os.environ.get('RENDER'):
        raise RuntimeError('DATABASE_URL is required on Render. Startup stopped to prevent data loss in temporary SQLite storage.')
    c = sqlite3.connect(path, timeout=20)
    c.row_factory = sqlite3.Row
    c.execute('PRAGMA foreign_keys=ON')
    return c
